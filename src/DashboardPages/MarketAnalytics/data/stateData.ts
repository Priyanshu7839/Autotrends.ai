export function getColorForSales(sales: number): string {
  const maxSales = 125000000;
  const minSales = 500000;
  const normalizedValue = (sales - minSales) / (maxSales - minSales);

  if (normalizedValue < 0.2) return "#e6f4ff";
  if (normalizedValue < 0.4) return "#b3dcff";
  if (normalizedValue < 0.6) return "#66b3ff";
  if (normalizedValue < 0.8) return "#3399ff";
  return "#0b85ff";
}
